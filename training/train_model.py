import glob
import os
import warnings

import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
from sklearn.neural_network import MLPClassifier
from sklearn.preprocessing import StandardScaler

warnings.filterwarnings("ignore")

LABELS = ["sitting", "standing", "walking", "running"]
WIN = 80            # 4 s x 20 Hz
HOP = 20            # one window every 1 s
MIN_SECONDS = 40    # skip recordings shorter than this


def load_recording(path):
    """Read one recording, resample onto an exact 50 ms grid (fills dropped packets), drop the first 2 s."""
    d = pd.read_csv(path)
    t = d.t_ms.values
    grid = np.arange(t[0], t[-1] + 1, 50)
    cols = ["ax", "ay", "az", "gx", "gy", "gz"]
    data = np.stack([np.interp(grid, t, d[c].values) for c in cols], axis=1)
    return data[40:]


def features(w):
    """Compute the 13 features of one 4 s window. computeFeatures() on the board does the same."""
    w = w.astype(np.float32)
    acc, gyr = w[:, :3], w[:, 3:]
    mag = np.sqrt((acc * acc).sum(axis=1))          # acceleration magnitude
    centered = mag - mag.mean()
    crossings = np.sum((centered[1:] >= 0) != (centered[:-1] >= 0))
    return np.concatenate([
        acc.mean(axis=0),        # 3: gravity direction = arm orientation
        acc.std(axis=0),         # 3: acceleration variability
        gyr.std(axis=0),         # 3: angular velocity variability
        [mag.mean(), mag.std(), mag.max() - mag.min(), crossings],   # 4: overall intensity and rhythm
    ]).astype(np.float32)


def train(X, y):
    """Balance the classes by oversampling, standardize the features, train the network."""
    n = max((y == k).sum() for k in range(len(LABELS)))
    idx = np.concatenate([
        np.random.RandomState(0).choice(np.where(y == k)[0], n) for k in range(len(LABELS))
    ])
    scaler = StandardScaler().fit(X[idx])
    net = MLPClassifier(hidden_layer_sizes=(16,), alpha=1e-2, max_iter=3000, random_state=0)
    net.fit(scaler.transform(X[idx]), y[idx])
    return scaler, net


def c_array(name, values):
    values = np.asarray(values, np.float32).ravel()
    body = ", ".join(f"{v:.6g}f" for v in values)
    return f"const float {name}[{len(values)}] = {{\n  {body}\n}};\n"


def find_recordings():
    """Look in the current folder, then ./data next to the script, then the script folder."""
    here = os.path.dirname(os.path.abspath(__file__))
    for folder in [os.getcwd(), os.path.join(here, "data"), here]:
        files = [f for f in sorted(glob.glob(os.path.join(folder, "*.csv")))
                 if os.path.basename(f).split("_")[0] in LABELS]
        if files:
            return folder, files
    return None, []


def main():
    folder, paths = find_recordings()
    if not paths:
        print("No recordings found (sitting_... / standing_... / walking_... / running_....csv)")
        return
    print(f"Reading recordings from: {folder}")
    X, y, rec, names = [], [], [], []
    for path in paths:
        label = os.path.basename(path).split("_")[0]
        data = load_recording(path)
        if len(data) < MIN_SECONDS * 20:
            continue
        names.append(os.path.basename(path))
        for start in range(0, len(data) - WIN + 1, HOP):
            X.append(features(data[start:start + WIN]))
            y.append(LABELS.index(label))
            rec.append(len(names) - 1)
    X, y, rec = np.array(X), np.array(y), np.array(rec)

    print(f"Using {len(names)} recordings, {len(y)} windows")
    for k, name in enumerate(LABELS):
        print(f"  {name}: {(y == k).sum()} windows")

    # Evaluation: each recording in turn is held out entirely and used as the test set
    pred = np.empty_like(y)
    for r in np.unique(rec):
        held_out = rec == r
        scaler, net = train(X[~held_out], y[~held_out])
        pred[held_out] = net.predict(scaler.transform(X[held_out]))
    print(f"\nLeave-one-recording-out accuracy: {accuracy_score(y, pred):.1%}")
    print("Confusion matrix (rows = true activity, columns = predicted):")
    print(pd.DataFrame(confusion_matrix(y, pred), index=LABELS, columns=LABELS))
    print("\nPer-class precision, recall and F1:")
    print(classification_report(y, pred, target_names=LABELS, digits=3))

    # Final model: train on all data and export the parameters
    scaler, net = train(X, y)
    train_acc = accuracy_score(y, net.predict(scaler.transform(X)))
    print(f"Training accuracy (on the training data itself, optimistic): {train_acc:.1%}")
    w1, w2 = net.coefs_
    b1, b2 = net.intercepts_
    with open("model_data.h", "w") as f:
        f.write("// Generated by train_model.py: 13 features -> 16 hidden units -> 4 classes\n")
        f.write("#define N_FEAT 13\n#define N_HID 16\n#define N_CLASS 4\n")
        f.write(c_array("F_MEAN", scaler.mean_))
        f.write(c_array("F_SCALE", scaler.scale_))
        f.write(c_array("NN_W1", w1.T))
        f.write(c_array("NN_B1", b1))
        f.write(c_array("NN_W2", w2.T))
        f.write(c_array("NN_B2", b2))
    print("\nModel parameters written to model_data.h")


if __name__ == "__main__":
    main()
